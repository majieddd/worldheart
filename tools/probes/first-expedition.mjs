import {resolve} from 'node:path';
export async function run({page,browser,base,out,check,errors}){
  await page.goto(base+'/lobby.html?onboarding=1');
  await page.waitForSelector('.first-intro[open]');
  await page.waitForTimeout(650);
  check('Opening types red text',await page.locator('.first-type span').evaluate(el=>el.textContent.length>1&&el.textContent.length<40));
  await page.waitForSelector('.first-cinema');await page.screenshot({path:resolve(out,'cinematic.png')});
  await page.locator('.first-skip').click();
  await page.getByRole('button',{name:'Replay opening'}).click();await page.locator('.first-skip').click();
  await page.waitForSelector('.first-story[open]');await page.screenshot({path:resolve(out,'story-desktop.png')});
  check('Four illustrated story panels',await page.locator('.first-panels figure').count()===4);
  await page.setViewportSize({width:390,height:844});await page.screenshot({path:resolve(out,'story-mobile.png')});
  check('Story stays within mobile viewport',await page.locator('.first-story').evaluate(el=>el.scrollWidth<=el.clientWidth+1&&el.getBoundingClientRect().right<=innerWidth));
  await page.getByRole('button',{name:'Begin first defense'}).click();
  await page.setViewportSize({width:1440,height:1000});
  await page.goto(base+'/?map=ninetynine&campaign=0&seed=12345&onboarding=1');
  await page.waitForFunction(()=>window.WH?.onboarding,null,{timeout:180000});
  if(await page.locator('.first-skip').count())await page.locator('.first-skip').click();
  await page.getByRole('button',{name:'Begin first defense'}).click();
  await page.waitForFunction(()=>WH.game.state==='playing');
  check('Arrival possesses commander in third person',await page.evaluate(()=>WH.possession.unit===WH.mode99.commander&&WH.possession.boomWant===4));
  check('Wave held for basic lessons',await page.evaluate(()=>WH.onboarding.holding&&WH.waves.wave===0));
  await page.keyboard.down('KeyW');await page.waitForTimeout(1800);await page.keyboard.up('KeyW');
  check('Real movement completes move lesson',await page.evaluate(()=>WH.onboarding.state.done.includes('move')));
  await page.locator('#view').click({position:{x:700,y:500}});await page.waitForTimeout(500);
  check('Real attack completes attack lesson',await page.evaluate(()=>WH.onboarding.state.done.includes('attack')));
  await page.screenshot({path:resolve(out,'third-person-guide.png')});
  await page.evaluate(()=>{document.exitPointerLock?.();WH.possession.exit();WH.rig.flyTo(WH.world.heart.group.position,WH.rig.defaultDist,.1);});
  await page.waitForTimeout(700);await page.locator('.build-card[data-type="bolt"]').click();
  const placed=await page.evaluate(async()=>{
    const {surfacePoint}=await import('./js/world.js');const g=WH.game,def=WH.TOWER_TYPES.bolt,dir=g.cursorDir.clone();
    for(let i=0;i<WH.nav.n;i++){
      WH.nav.nodeDir(i,dir);if(dir.dot(g.frontier.centre)<Math.cos(g.frontier.theta*.85))continue;
      g.cursorDir.copy(dir);surfacePoint(dir,g.cursorPos);g.cursorValid=true;
      if(!g._validate(def).ok)continue;g._tryPlace();g.cancelBuild();return true;
    }return false;
  });await page.waitForTimeout(100);
  check('Fixture: production placement releases wave gate',placed&&await page.evaluate(()=>WH.onboarding.state.done.includes('tower')&&!WH.game.onboardingHold));
  await page.evaluate(()=>{const m=WH.mode99;m.crystals.register('qa-first');m.crystals.pickup('qa-first');});await page.waitForTimeout(100);
  check('Fixture: crystal pickup changes objective to return',await page.evaluate(()=>WH.onboarding.lesson==='deposit'));
  await page.evaluate(()=>{WH.mode99.commander.dir.copy(WH.game.frontier.centre);WH.mode99.depositCrystals();});await page.waitForTimeout(100);
  check('Fixture: real deposit receipt advances objective',await page.evaluate(()=>WH.onboarding.lesson==='upgrade'));
  await page.evaluate(()=>{WH.give(5000);WH.mode99.upgradeHeart();});await page.waitForTimeout(100);
  check('Fixture: base upgrade completes core lessons',await page.evaluate(()=>WH.onboarding.lesson===null));
  await page.evaluate(()=>{WH.waves.wave=1;WH.onboarding.update();});
  check('Contextual skill briefing',await page.locator('.first-guide h2').textContent()==='Two powers, one defender');
  await page.getByRole('button',{name:'Got it',exact:true}).click();
  await page.evaluate(()=>{WH.waves.wave=10;WH.onboarding.update();});
  check('Contextual boss briefing',await page.locator('.first-guide h2').textContent()==='A boss approaches');
  await page.getByRole('button',{name:'Got it',exact:true}).click();
  await page.evaluate(()=>{const run=WH.mode99.run,original=run.getPhase;run.getPhase=()=> 'victory';WH.onboarding.update();run.getPhase=original;});
  check('Fixture: victory explains Endless',await page.locator('.first-guide h2').textContent()==='Your first defense is complete');
  await page.getByRole('button',{name:'Got it',exact:true}).click();
  await page.evaluate(()=>{const run=WH.mode99.run,original=run.getConquestWave;run.getConquestWave=()=>11;WH.onboarding.update();run.getConquestWave=original;});
  check('Fixture: full base explains conquest boss',await page.locator('.first-guide h2').textContent()==='The planet fights back');
  await page.getByRole('button',{name:'Got it',exact:true}).click();
  await page.evaluate(()=>{const run=WH.mode99.run,original=run.hasConquered;run.hasConquered=()=>true;WH.onboarding.update();run.hasConquered=original;});
  check('Fixture: conquered planet explains homeworld rules',await page.locator('.first-guide h2').textContent()==='A world of your own');
  await page.locator('[data-skip]').click();
  check('Skip immediately releases waves',await page.evaluate(()=>!WH.game.onboardingHold));
  const touch=await browser.newContext({viewport:{width:390,height:844},isMobile:true,hasTouch:true,deviceScaleFactor:1,reducedMotion:'reduce'}),mobile=await touch.newPage();
  await mobile.goto(base+'/lobby.html?onboarding=1');await mobile.waitForSelector('.first-skip');await mobile.locator('.first-skip').tap();
  await mobile.getByRole('button',{name:'Replay opening'}).tap();await mobile.locator('.first-skip').tap();await mobile.getByRole('button',{name:'Begin first defense'}).tap();
  check('Real touch dismisses and replays presentation',await mobile.locator('dialog[open]').count()===0);
  await mobile.goto(base+'/?map=ninetynine&campaign=1&seed=12345');await mobile.waitForSelector('.first-story[open]',{timeout:180000});await mobile.getByRole('button',{name:'Begin first defense'}).tap();
  await mobile.waitForFunction(()=>WH.onboarding?.holding);await mobile.waitForTimeout(750);await mobile.screenshot({path:resolve(out,'mobile-first-defense.png')});
  check('Fresh campaign begins in third person with touch controls',await mobile.evaluate(()=>WH.possession.unit===WH.mode99.commander&&WH.possession.boomWant===4&&!!WH.mobile));
  await mobile.locator('[data-skip]').tap();await mobile.reload();await mobile.waitForFunction(()=>window.WH?.onboarding,null,{timeout:180000});
  check('Returning campaign does not force the story again',await mobile.locator('.first-story[open]').count()===0);
  await touch.close();
  check('No runtime errors',errors.length===0,errors);
}
